// Trims the public Egyptian drug database to the three fields the prescription search needs and
// writes them as a TypeScript module, so the list is compiled into dist/ and needs no file path at runtime.
//
// 1. Download the dataset next to this script:
//      curl -L -o apps/api/scripts/egyptian-drugs.json \
//        https://raw.githubusercontent.com/karem505/egyptian-drug-database/main/data/egyptian-drugs.json
// 2. Run:  node apps/api/scripts/build-drug-catalogue.mjs
// Source data is CC0 (https://github.com/karem505/egyptian-drug-database).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "egyptian-drugs.json");
const target = join(here, "..", "src", "modules", "clinical", "drug-data.ts");

const clean = (value) => String(value ?? "").replace(/[|\r\n]+/g, " ").replace(/\s+/g, " ").trim();

const seen = new Set();
const rows = [];
for (const drug of JSON.parse(readFileSync(source, "utf8"))) {
  const en = clean(drug.commercial_name_en);
  if (en === "" || seen.has(en)) continue;
  seen.add(en);
  rows.push(`${en}|${clean(drug.commercial_name_ar)}|${clean(drug.scientific_name)}`);
}

writeFileSync(
  target,
  [
    "// Generated by apps/api/scripts/build-drug-catalogue.mjs from the CC0 Egyptian drug database. Do not edit.",
    '// Each row is "English commercial name|Arabic commercial name|scientific name".',
    "",
    "export const DRUG_ROWS: readonly string[] = " + JSON.stringify(rows) + ";",
    "",
  ].join("\n"),
);
console.log(`${rows.length} drugs written to ${target}`);
