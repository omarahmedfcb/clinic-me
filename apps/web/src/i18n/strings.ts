const CATALOGUES: Record<Locale, Partial<Record<TranslationKey, string>>> = {
  ar: AR,
  en: EN,
};

/**
 * Looks up a string for a locale, falling back to the key itself.
 *
 * There is deliberately no fallback *through* Arabic: a missing English string renders as
 * `nav.patients`, not as Arabic text inside an English page.
 */
export function translate(locale: Locale, key: TranslationKey): string {
  return CATALOGUES[locale][key] ?? key;
}

/**
 * Binds a locale, giving the `t()` the components call. The React context that supplies this
 * arrives with the authenticated shell; until then callers bind it explicitly.
 */
export function translatorFor(locale: Locale): (key: TranslationKey) => string {
  return (key) => translate(locale, key);
}

/** The Arabic translator, for code that runs before a locale has been resolved. */
export const t = translatorFor(DEFAULT_LOCALE);

/**
 * Which keys a locale is missing. Used by the catalogue-completeness test, and the honest way to
 * answer "how translated is the English interface" — currently: not at all, by decision.
 */
export function missingKeys(locale: Locale): TranslationKey[] {
  const catalogue = CATALOGUES[locale];
  return (Object.keys(AR) as TranslationKey[]).filter((key) => catalogue[key] === undefined);
}

export const ALL_TRANSLATION_KEYS = Object.keys(AR) as readonly TranslationKey[];
