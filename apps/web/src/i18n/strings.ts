/**
 * The string catalogue and the `t()` lookup (SCHEMA-DECISIONS.md D20).
 *
 * ## Arabic is the catalogue, not a translation of one
 *
 * `ar` is complete and `en` is empty. That is the agreed shape: the plumbing is what is expensive
 * to retrofit, the translations are not, and shipping an English catalogue nobody has reviewed
 * would be worse than shipping none — a half-translated interface reads as broken in a way that an
 * untranslated one does not.
 *
 * ## A missing string falls back to its key, visibly
 *
 * `t("nav.patients")` in English returns `nav.patients`. It does **not** fall back to the Arabic,
 * and that is deliberate: an Arabic string appearing inside an otherwise-English page looks like a
 * rendering bug and gets reported as one, while a dotted key is unmistakably "nobody has written
 * this yet". The failure should be legible to whoever sees it.
 *
 * Keys are dotted and grouped by surface. `TranslationKey` is derived from the Arabic catalogue,
 * so `t()` cannot be called with a key that does not exist — a typo is a compile error, not a
 * string that renders as itself in production.
 */

